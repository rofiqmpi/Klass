enum class ThemeMode {
    LIGHT,
    DARK,
    DEFAULT;

    fun getDisplayName(): String = when (this) {
        LIGHT -> "লাইট মোড"
        DARK -> "ডার্ক মোড"
        DEFAULT -> "সিস্টেম ডিফল্ট"
    }
}

